import { requestGemini } from './_gemini.js';

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const text = req.body?.text;
  if (typeof text !== 'string' || !text.trim()) {
    return res.status(400).json({ error: 'No text provided' });
  }

  try {
    const data = await requestGemini({
      system_instruction: {
        parts: [{
          text: 'You are a professional study assistant. Return ONLY a valid JSON array of flashcards in the format [{"question":"...","answer":"..."}]. Do not include markdown or explanations.'
        }]
      },
      contents: [{ parts: [{ text: text.trim() }] }],
      generationConfig: {
        response_mime_type: 'application/json',
        temperature: 0.3,
        maxOutputTokens: 2048
      }
    });

    const generatedText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!generatedText) throw new Error('No content was generated by the AI');

    const flashcards = JSON.parse(generatedText);
    if (!Array.isArray(flashcards)) throw new Error('The AI returned an invalid flashcard format');
    return res.status(200).json({ flashcards });
  } catch (error) {
    console.error('Flashcard generation error:', error);
    return res.status(500).json({ error: error.message || 'Unable to generate flashcards' });
  }
}