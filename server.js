import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';

dotenv.config();

const app = express();
app.use(cors());
app.use(express.json({ limit: '50mb' }));

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;

if (!GEMINI_API_KEY) {
  console.error('❌ ERROR: GEMINI_API_KEY is not set in .env file!');
  console.error('Please create a .env file with: GEMINI_API_KEY=your_key_here');
  process.exit(1);
}

// Updated server.js logic for modern Gemini 1.5 Flash
// Updated server.js for secure and modern Gemini usage
app.post('/api/generate-flashcards', async (req, res) => {
  try {
    const { text } = req.body;

    if (!text || text.trim().length === 0) {
      return res.status(400).json({ error: 'No text provided' });
    }

    // Using the STABLE Gemini 1.5 Flash endpoint
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          // SECURITY: Isolate rules from user data using system_instruction
          system_instruction: {
            parts: [{
              text: "You are a professional study assistant. Analyze the provided text and return ONLY a valid JSON array of flashcards. " +
                    "Format: [{\"question\": \"...\", \"answer\": \"...\"}]. Do not include markdown or explanations."
            }]
          },
          contents: [{
            parts: [{ text: text }] // User data is strictly separated
          }],
          generationConfig: {
            // RELIABILITY: Force the model to output valid JSON
            response_mime_type: "application/json",
            temperature: 0.3,
            maxOutputTokens: 2048,
          }
        })
      }
    );

    if (!response.ok) {
      const errorData = await response.json();
      throw new Error(errorData.error?.message || 'Gemini API Error');
    }

    const data = await response.json();
    
    // Extract text from the modern response format
    const generatedText = data.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!generatedText) {
      throw new Error('No content was generated by the AI');
    }

    // Because we used response_mime_type, we can parse directly
    const flashcards = JSON.parse(generatedText);
    res.json({ flashcards });

  } catch (error) {
    console.error('❌ Server Error:', error.message);
    res.status(500).json({ error: error.message });
  }
});

// API key validation endpoint
app.get('/api/validate-key', async (req, res) => {
  try {
    const testResp = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{
            parts: [{ text: 'Hello' }]
          }],
          generationConfig: { maxOutputTokens: 10 }
        })
      }
    );

    if (!testResp.ok) {
      const text = await testResp.text();
      let apiMessage = testResp.statusText;
      try {
        const parsed = JSON.parse(text);
        apiMessage = parsed?.error?.message || parsed?.message || apiMessage;
      } catch (e) {}
      return res.status(200).json({ valid: false, message: apiMessage });
    }

    return res.json({ valid: true });
  } catch (e) {
    console.error('Key validation error:', e);
    return res.status(500).json({ valid: false, message: e.message });
  }
});

// Health check endpoint
app.get('/health', (req, res) => {
  res.json({ 
    status: 'ok', 
    message: 'FlashGen backend is running',
    apiKeyConfigured: !!GEMINI_API_KEY 
  });
});

// 404 handler
app.use((req, res) => {
  res.status(404).json({ error: 'Endpoint not found', path: req.path });
});

// Error handler
// eslint-disable-next-line no-unused-vars
app.use((err, req, res, next) => {
  console.error('Unhandled server error:', err);
  const status = err.status || 500;
  res.status(status).json({ error: err.message || 'Internal Server Error' });
});

const PORT = 3001;
app.listen(PORT, () => {
  console.log('=================================');
  console.log(`✅ FlashGen Backend Server`);
  console.log(`📡 Running on port ${PORT}`);
  console.log(`🔑 API Key: ${GEMINI_API_KEY ? 'Configured ✓' : 'Missing ✗'}`);
  console.log(`🤖 Model: Gemini 1.5 Flash`);
  console.log('=================================');
});